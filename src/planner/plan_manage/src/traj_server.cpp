double alpha_max_ = 2.0;
double alpha_safety_ratio_ = 0.90;
double alpha_rate_up_ = 1.5;
double alpha_rate_down_ = 5.0;

double evtr_lookahead_time_ = 0.4;
int evtr_lookahead_samples_ = 5;
double evtr_eps_vel_ = 1e-3;
double evtr_eps_acc_ = 1e-3;

bool enable_alpha_dot_acc_ = true;

bool evtr_fallback_this_cycle_ = false;
std::string evtr_fallback_reason_ = "none";
int evtr_fallback_count_ = 0;

bool is_flight_started_ = false;
ros::Time start_flight_time_;
