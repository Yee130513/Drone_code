void bsplineCallback(traj_utils::BsplineConstPtr msg)
{
  // parse pos traj

  Eigen::MatrixXd pos_pts(3, msg->pos_pts.size());

  Eigen::VectorXd knots(msg->knots.size());
  for (size_t i = 0; i < msg->knots.size(); ++i)
  {
    knots(i) = msg->knots[i];
  }

  for (size_t i = 0; i < msg->pos_pts.size(); ++i)
  {
    pos_pts(0, i) = msg->pos_pts[i].x;
    pos_pts(1, i) = msg->pos_pts[i].y;
    pos_pts(2, i) = msg->pos_pts[i].z;
  }

  UniformBspline pos_traj(pos_pts, msg->order, 0.1);
  pos_traj.setKnot(knots);

  // parse yaw traj

  // Eigen::MatrixXd yaw_pts(msg->yaw_pts.size(), 1);
  // for (int i = 0; i < msg->yaw_pts.size(); ++i) {
  //   yaw_pts(i, 0) = msg->yaw_pts[i];
  // }

  //UniformBspline yaw_traj(yaw_pts, msg->order, msg->yaw_dt);

  start_time_ = msg->start_time;
  traj_id_ = msg->traj_id;

  traj_.clear();
  traj_.push_back(pos_traj);
  traj_.push_back(traj_[0].getDerivative());
  traj_.push_back(traj_[1].getDerivative());

  traj_duration_ = traj_[0].getTimeSum();

  receive_traj_ = true;
}

std::pair<double, double> calculate_yaw(double progress_time, Eigen::Vector3d &pos, ros::Time &time_now, ros::Time &time_last)
{
  constexpr double PI = 3.1415926;
  constexpr double YAW_DOT_MAX_PER_SEC = PI;
  // constexpr double YAW_DOT_DOT_MAX_PER_SEC = PI;
  std::pair<double, double> yaw_yawdot(0, 0);
  double yaw = 0;
  double yawdot = 0;

  Eigen::Vector3d dir = progress_time + time_forward_ <= traj_duration_ ? traj_[0].evaluateDeBoorT(progress_time + time_forward_) - pos : traj_[0].evaluateDeBoorT(traj_duration_) - pos;
  double yaw_temp = dir.norm() > 0.1 ? atan2(dir(1), dir(0)) : last_yaw_;

  double max_yaw_change = YAW_DOT_MAX_PER_SEC * (time_now - time_last).toSec();
  if (yaw_temp - last_yaw_ > PI)
  {
    if (yaw_temp - last_yaw_ - 2 * PI < -max_yaw_change)
    {
      yaw = last_yaw_ - max_yaw_change;
      if (yaw < -PI)
        yaw += 2 * PI;

      yawdot = -YAW_DOT_MAX_PER_SEC;
    }
    else
    {
      yaw = yaw_temp;
      if (yaw - last_yaw_ > PI)
        yawdot = -YAW_DOT_MAX_PER_SEC;
      else
        yawdot = (yaw_temp - last_yaw_) / (time_now - time_last).toSec();
    }
  }
  else if (yaw_temp - last_yaw_ < -PI)
  {
    if (yaw_temp - last_yaw_ + 2 * PI > max_yaw_change)
    {
      yaw = last_yaw_ + max_yaw_change;
      if (yaw > PI)
        yaw -= 2 * PI;

      yawdot = YAW_DOT_MAX_PER_SEC;
    }
    else
    {
      yaw = yaw_temp;
      if (yaw - last_yaw_ < -PI)
        yawdot = YAW_DOT_MAX_PER_SEC;
      else
        yawdot = (yaw_temp - last_yaw_) / (time_now - time_last).toSec();
    }
  }
  else
  {
    if (yaw_temp - last_yaw_ < -max_yaw_change)
    {
      yaw = last_yaw_ - max_yaw_change;
      if (yaw < -PI)
        yaw += 2 * PI;

      yawdot = -YAW_DOT_MAX_PER_SEC;
    }
    else if (yaw_temp - last_yaw_ > max_yaw_change)
    {
      yaw = last_yaw_ + max_yaw_change;
      if (yaw > PI)
        yaw -= 2 * PI;

      yawdot = YAW_DOT_MAX_PER_SEC;
    }
    else
    {
      yaw = yaw_temp;
      if (yaw - last_yaw_ > PI)
        yawdot = -YAW_DOT_MAX_PER_SEC;
      else if (yaw - last_yaw_ < -PI)
        yawdot = YAW_DOT_MAX_PER_SEC;
      else
        yawdot = (yaw_temp - last_yaw_) / (time_now - time_last).toSec();
    }
  }

  if (fabs(yaw - last_yaw_) <= max_yaw_change)
    yaw = 0.5 * last_yaw_ + 0.5 * yaw; // nieve LPF
  yawdot = 0.5 * last_yaw_dot_ + 0.5 * yawdot;
  last_yaw_ = yaw;
  last_yaw_dot_ = yawdot;

  yaw_yawdot.first = yaw;
  yaw_yawdot.second = yawdot;

  return yaw_yawdot;
}

inline double clampDouble(double x, double lo, double hi)
{
  return std::max(lo, std::min(x, hi));
}

inline bool isFiniteVec(const Eigen::Vector3d &v)
{
  return std::isfinite(v.x()) && std::isfinite(v.y()) && std::isfinite(v.z());
}

inline double safeEvalTime(double s)
{
  constexpr double kEps = 1e-4;
  if (traj_duration_ <= kEps)
    return 0.0;
  return clampDouble(s, 0.0, traj_duration_ - kEps);
}

bool computeLookaheadAlpha(double s_now, double &alpha_allow, std::string &reason)
{
  if (traj_.size() < 3 || traj_duration_ <= 1e-4)
  {
    reason = "invalid_traj";
    return false;
  }

  const int sample_count = std::max(1, evtr_lookahead_samples_);
  const double horizon = std::max(0.0, evtr_lookahead_time_);
  double alpha_min_window = alpha_max_;

  for (int k = 0; k <= sample_count; ++k)
  {
    const double ratio = static_cast<double>(k) / static_cast<double>(sample_count);
    const double s = safeEvalTime(s_now + ratio * horizon);

    Eigen::Vector3d v_spline = traj_[1].evaluateDeBoorT(s);
    Eigen::Vector3d a_spline = traj_[2].evaluateDeBoorT(s);

    if (!isFiniteVec(v_spline) || !isFiniteVec(a_spline))
    {
      reason = "nan_derivative";
      return false;
    }

    const double v_norm = v_spline.norm();
    const double a_norm = a_spline.norm();
    const double alpha_v = max_vel_ / (v_norm + evtr_eps_vel_);
    const double alpha_a = std::sqrt(max_acc_ / (a_norm + evtr_eps_acc_));
    const double alpha_local = std::min(alpha_v, alpha_a);

    alpha_min_window = std::min(alpha_min_window, alpha_local);
  }

  alpha_allow = alpha_safety_ratio_ * alpha_min_window;
  reason = "none";
  return std::isfinite(alpha_allow);
}

double rateLimitAlpha(double alpha_raw, double alpha_prev, double dt)
{
  const double delta = alpha_raw - alpha_prev;
  const double max_up = alpha_rate_up_ * dt;
  const double max_down = alpha_rate_down_ * dt;
  const double delta_limited = clampDouble(delta, -max_down, max_up);
  return alpha_prev + delta_limited;
}

void cmdCallback(const ros::TimerEvent &e)
{
  if (!receive_traj_)
    return;

  ros::Time time_now = ros::Time::now();
  double t_cur = (time_now - start_time_).toSec();

  static ros::Time time_last = ros::Time::now();
  ros::Time time_last_for_yaw = time_last;
  double dt = (time_now - time_last).toSec();
  if (dt <= 0.0 || dt > 0.05)
    dt = 0.01;
  time_last_for_yaw = time_now - ros::Duration(dt);
  time_last = time_now;

  Eigen::Vector3d pos(Eigen::Vector3d::Zero()), vel(Eigen::Vector3d::Zero()), acc(Eigen::Vector3d::Zero()), pos_f;
  std::pair<double, double> yaw_yawdot(0, 0);

  if (traj_id_ != last_traj_id_)
  {
    s_virtual_ = 0.0;
    alpha_prev_ = std::min(alpha_prev_, 1.0);
    alpha_curr_ = alpha_prev_;
    alpha_dot_ = 0.0;
    last_traj_id_ = traj_id_;
  }

  double progress_time = clampDouble(t_cur, 0.0, traj_duration_);
  double alpha = 1.0;
  double alpha_dot = 0.0;
  evtr_fallback_this_cycle_ = false;
  evtr_fallback_reason_ = "none";

  if (enable_virtual_time_remap_)
  {
    double alpha_allow = 1.0;
    std::string reason;

    if (computeLookaheadAlpha(s_virtual_, alpha_allow, reason))
    {
      const double alpha_raw = clampDouble(alpha_allow, alpha_min_, alpha_max_);
      alpha_curr_ = rateLimitAlpha(alpha_raw, alpha_prev_, dt);
      alpha_curr_ = clampDouble(alpha_curr_, alpha_min_, alpha_max_);
      alpha_dot_ = (alpha_curr_ - alpha_prev_) / dt;

      s_virtual_ += 0.5 * (alpha_prev_ + alpha_curr_) * dt;
      s_virtual_ = clampDouble(s_virtual_, 0.0, traj_duration_);

      alpha = alpha_curr_;
      alpha_dot = alpha_dot_;
      progress_time = s_virtual_;
    }
    else
    {
      evtr_fallback_this_cycle_ = true;
      evtr_fallback_reason_ = reason;
      evtr_fallback_count_++;
      alpha = 1.0;
      alpha_dot = 0.0;
      progress_time = clampDouble(t_cur, 0.0, traj_duration_);
    }
  }

  if (progress_time < traj_duration_ && progress_time >= 0.0 && traj_.size() >= 3)
  {
    const double safe_p = safeEvalTime(progress_time);
    pos = traj_[0].evaluateDeBoorT(safe_p);
    Eigen::Vector3d p_s = traj_[1].evaluateDeBoorT(safe_p);
    Eigen::Vector3d p_ss = traj_[2].evaluateDeBoorT(safe_p);

    if (!enable_virtual_time_remap_ || evtr_fallback_this_cycle_)
    {
      vel = p_s;
      acc = p_ss;
    }
    else
    {
      vel = p_s * alpha;
      if (enable_alpha_dot_acc_)
      {
        acc = p_ss * (alpha * alpha) + p_s * alpha_dot;
      }
      else
      {
        acc = p_ss * (alpha * alpha);
      }
    }

    const double acc_guard = std::max(max_acc_ * 2.0, max_acc_ + 1.0);
    if (enable_virtual_time_remap_ && !evtr_fallback_this_cycle_ && acc.norm() > acc_guard)
    {
      evtr_fallback_this_cycle_ = true;
      evtr_fallback_reason_ = "acc_cmd_too_large";
      evtr_fallback_count_++;
      alpha = 1.0;
      alpha_dot = 0.0;
      progress_time = clampDouble(t_cur, 0.0, traj_duration_);

      const double fallback_s = safeEvalTime(progress_time);
      pos = traj_[0].evaluateDeBoorT(fallback_s);
      vel = traj_[1].evaluateDeBoorT(fallback_s);
      acc = traj_[2].evaluateDeBoorT(fallback_s);
    }

    if (!isFiniteVec(pos) || !isFiniteVec(vel) || !isFiniteVec(acc))
    {
      pos = traj_[0].evaluateDeBoorT(0.0);
      vel.setZero();
      acc.setZero();
      evtr_fallback_this_cycle_ = true;
      evtr_fallback_reason_ = "nan_cmd";
      evtr_fallback_count_++;
    }

    yaw_yawdot = calculate_yaw(progress_time, pos, time_now, time_last_for_yaw);
    double tf = min(traj_duration_, progress_time + 2.0);
    pos_f = traj_[0].evaluateDeBoorT(tf);
  }
  else
  {
    pos = traj_[0].evaluateDeBoorT(traj_duration_);
    vel.setZero();
    acc.setZero();

    yaw_yawdot.first = last_yaw_;
    yaw_yawdot.second = 0;
    pos_f = pos;
  }

  if (enable_virtual_time_remap_ && !evtr_fallback_this_cycle_)
  {
    alpha_prev_ = alpha_curr_;
  }
  else
  {
    alpha_prev_ = 1.0;
    alpha_curr_ = 1.0;
    alpha_dot_ = 0.0;
  }

  if (!is_flight_started_)
  {
    start_flight_time_ = ros::Time::now();
    is_flight_started_ = true;
  }

  double t_current = (ros::Time::now() - start_flight_time_).toSec();

  static double last_record_time = 0;
  if (progress_time < traj_duration_ && t_current - last_record_time > 0.1)
  {
    const char *home_env = getenv("HOME");
    if (home_env != nullptr)
    {
      std::string home_dir(home_env);
      std::ofstream real_profile(home_dir + "/.ros/ego_real_flight_log.csv", std::ios::out | std::ios::app);
      if (real_profile.is_open())
      {
        if (real_profile.tellp() == 0)
        {
          real_profile << "Real_Time,ProgressTime,Alpha,AlphaDot,Velocity,Acceleration,EVTR_Enable,EVTR_Fallback,FallbackReason\n";
        }
        real_profile << t_current << ","
                     << progress_time << ","
                     << alpha << ","
                     << alpha_dot << ","
                     << vel.norm() << ","
                     << acc.norm() << ","
                     << (enable_virtual_time_remap_ ? 1 : 0) << ","
                     << (evtr_fallback_this_cycle_ ? 1 : 0) << ","
                     << evtr_fallback_reason_ << "\n";
        real_profile.close();
      }
    }
    last_record_time = t_current;
  }

  // ---------------- 发送指令 ----------------
  cmd.header.stamp = time_now;
  cmd.header.frame_id = "world";
  cmd.trajectory_flag = quadrotor_msgs::PositionCommand::TRAJECTORY_STATUS_READY;
  cmd.trajectory_id = traj_id_;

  cmd.position.x = pos(0);
  cmd.position.y = pos(1);
  cmd.position.z = pos(2);

  cmd.velocity.x = vel(0);
  cmd.velocity.y = vel(1);
  cmd.velocity.z = vel(2);

  cmd.acceleration.x = acc(0);
  cmd.acceleration.y = acc(1);
  cmd.acceleration.z = acc(2);

  cmd.yaw = yaw_yawdot.first;
  cmd.yaw_dot = yaw_yawdot.second;

  last_yaw_ = cmd.yaw;

  pos_cmd_pub.publish(cmd);
}

int main(int argc, char **argv)
{
  ros::init(argc, argv, "traj_server");
  // ros::NodeHandle node;
  ros::NodeHandle nh("~");
  nh.param("traj_server/enable_virtual_time_remap", enable_virtual_time_remap_, false);
  nh.param("manager/max_vel", max_vel_, 1.5);
  nh.param("manager/max_acc", max_acc_, 5.0);
  nh.param("manager/time_scaling_method", time_scaling_method_, std::string("Global"));

  nh.param("traj_server/alpha_min", alpha_min_, 0.4);
  nh.param("traj_server/alpha_max", alpha_max_, 2.0);
  nh.param("traj_server/alpha_safety_ratio", alpha_safety_ratio_, 0.90);
  nh.param("traj_server/alpha_rate_up", alpha_rate_up_, 1.5);
  nh.param("traj_server/alpha_rate_down", alpha_rate_down_, 5.0);
  nh.param("traj_server/evtr_lookahead_time", evtr_lookahead_time_, 0.4);
  nh.param("traj_server/evtr_lookahead_samples", evtr_lookahead_samples_, 5);
  nh.param("traj_server/enable_alpha_dot_acc", enable_alpha_dot_acc_, true);

  ros::Subscriber bspline_sub = nh.subscribe("planning/bspline", 10, bsplineCallback);

  pos_cmd_pub = nh.advertise<quadrotor_msgs::PositionCommand>("/position_cmd", 50);

  ros::Timer cmd_timer = nh.createTimer(ros::Duration(0.01), cmdCallback);
  
  /* control parameter */
  cmd.kx[0] = pos_gain[0];
  cmd.kx[1] = pos_gain[1];
  cmd.kx[2] = pos_gain[2];

  cmd.kv[0] = vel_gain[0];
  cmd.kv[1] = vel_gain[1];
  cmd.kv[2] = vel_gain[2];

  nh.param("traj_server/time_forward", time_forward_, -1.0);
  last_yaw_ = 0.0;
  last_yaw_dot_ = 0.0;

  ros::Duration(1.0).sleep();

  ROS_WARN("[Traj server]: ready.");

  ros::spin();

  return 0;
}
